class VerifiedFundamentalProvider(FundamentalDataProvider):
    """
    Supplies audited, regulatory-filed financial disclosures.
    Refuses to fabricate figures for unverified entities, returning explicit provenance status.
    """
    def get_info(self) -> ProviderInfo:
        return ProviderInfo(
            id="verified_filings",
            name="Audited Exchange-Filed Disclosures Provider",
            provider_type="FUNDAMENTALS",
            description="Verified historical financial statements sourced directly from audited company annual reports filed with BSE/NSE.",
            is_enabled=True,
            is_license_approved=True,
            compliance_notice="Contains audited regulatory disclosures with full provenance, source references, and fiscal timestamps.",
            documentation_url="https://www.bseindia.com/corporates/ann.html",
            endpoint_url=None,
        )

    async def health_check(self) -> Dict[str, Any]:
        return {
            "status": "ONLINE",
            "licensed": True,
            "verified_symbols_count": len(VERIFIED_AUDITED_FILINGS),
            "coverage": list(VERIFIED_AUDITED_FILINGS.keys()),
            "timestamp": datetime.now(timezone.utc).isoformat(),
        }

    async def get_historical_financials(self, symbol: str) -> List[NormalizedFinancialPeriod]:
        sym = symbol.upper()
        if sym not in VERIFIED_AUDITED_FILINGS:
            # Does NOT fabricate data. Return empty list and indicate manual upload or entry required.
            return []

        raw_periods = VERIFIED_AUDITED_FILINGS[sym]
        retrieval_ts = datetime.now(timezone.utc).isoformat()
        
        results: List[NormalizedFinancialPeriod] = []
        for p in raw_periods:
            results.append(
                NormalizedFinancialPeriod(
                    fiscal_year=p["fiscal_year"],
                    fiscal_period=p["fiscal_period"],
                    revenue=p["revenue"],
                    operating_expenses=p["operating_expenses"],
                    ebit=p["ebit"],
                    ebit_margin_pct=p["ebit_margin_pct"],
                    tax_expense=p["tax_expense"],
                    effective_tax_rate_pct=p["effective_tax_rate_pct"],
                    depreciation_amortization=p["depreciation_amortization"],
                    capex=p["capex"],
                    working_capital=p["working_capital"],
                    change_in_nwc=p["change_in_nwc"],
                    cash_and_equivalents=p["cash_and_equivalents"],
                    total_debt=p["total_debt"],
                    minority_interest=p["minority_interest"],
                    diluted_shares=p["diluted_shares"],
                    reporting_unit="crore",
                    reporting_currency="INR",
                    provenance=p["provenance"],
                    source_document=p["source_document"],
                    source_url=p["source_url"],
                    retrieval_timestamp=retrieval_ts,
                )
            )
        return results
